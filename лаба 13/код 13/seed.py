"""Демонстрационные данные для фитнес-центра (ЛР13, вариант 8).

Не менее 20 документов; каждый содержит простые поля, вложенный объект
(address), массив (goals/training_days), статус и тренера.
"""


def seed_data() -> list[dict]:
    names = ["Иванов Иван", "Петрова Анна", "Сидоров Павел", "Козлов Артём",
             "Смоленская Ольга", "Морозов Кирилл", "Волкова Дарья", "Никитин Олег",
             "Белова Ирина", "Соколов Максим"]
    docs = []
    for i in range(1, 21):
        idx = (i - 1) % 10
        name = names[idx]
        year = 2000 - i % 20 + (1 if i % 3 == 0 else 0)
        age = max(18, min(60, 2024 - year))
        docs.append({
            "full_name": name + (f" {i}" if i > 10 else ""),
            "age": age,
            "phone": f"+7915{i:08d}",
            "status": "активен" if i % 5 != 0 else "заморожен",
            "registered_at": f"2024-{((i - 1) % 12) + 1:02d}-{((i % 27) + 1):02d}",
            "address": {"city": "Москва" if i % 2 else "Санкт-Петербург",
                        "street": f"Улица {i % 40}",
                        "house": i % 100 + 1},
            "goals": ["похудение"] if i % 3 == 0 else
                     (["набор массы"] if i % 3 == 1 else ["тонус", "выносливость"]),
            "training_days": ["пн", "ср", "пт"] if i % 2 == 0 else ["вт", "чт", "сб"],
            "trainer": "Тренер Мария" if i % 2 == 0 else "Тренер Сергей",
            "membership": {"kind": "месячный", "price": 3500,
                           "status": "активен", "start": "2024-09-01",
                           "end": "2024-10-01"},
        })
    return docs